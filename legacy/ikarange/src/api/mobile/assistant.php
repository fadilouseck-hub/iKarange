<?php

/**
 * In-app assistant for the insured apps: answers basic questions about the app and the member's cover.
 *
 * The apps never talk to the model provider: they call POST /api/mobile/v1/assistant/messages and this file
 * calls the Claude Messages API with the key kept in the server .env (ANTHROPIC_API_KEY). The site has no
 * Composer, so the call is plain HTTPS (curl extension, stream wrapper as a fallback).
 *
 * Privacy: the model receives the member's questions and a short contract summary (plan, status, coverage
 * rates, annual limit). No name, member number, phone, claim or medical record is sent, and the conversation
 * is not stored on this server (mobile_assistant_usage keeps one row per question for rate limiting).
 */

const ASSISTANT_API_URL = 'https://api.anthropic.com/v1/messages';
const ASSISTANT_DEFAULT_MODEL = 'claude-opus-5-5';
const ASSISTANT_MAX_TURNS = 12;
const ASSISTANT_MAX_CHARS = 1000;
const ASSISTANT_HOURLY_LIMIT = 30;
// Below the apps' 30 s request timeout.
const ASSISTANT_TIMEOUT = 25;

function assistantKey(): ?string
{
    $key = trim((string)(getenv('ANTHROPIC_API_KEY') ?: ''));
    return $key !== '' ? $key : null;
}

function assistantSuggestions(): array
{
    return [
        t('Comment déclarer un sinistre ?', 'How do I submit a claim?'),
        t('Comment utiliser ma carte chez un prestataire ?', 'How do I use my card at a provider?'),
        t('Quels sont mes taux de couverture ?', 'What are my coverage rates?'),
        t('Où trouver une pharmacie du réseau ?', 'Where can I find a network pharmacy?'),
    ];
}

function assistantInfo(): array
{
    return [
        'available' => assistantKey() !== null,
        'suggestions' => assistantSuggestions(),
        'disclaimer' => t(
            "Réponses générées par une IA : elles peuvent contenir des erreurs et ne remplacent ni votre gestionnaire ni un avis médical. N'indiquez pas d'informations médicales.",
            'Answers are generated by AI: they may contain mistakes and replace neither your account manager nor medical advice. Do not share medical information.'),
    ];
}

/** Validated conversation from the request: alternating user/assistant text turns ending with a user turn. */
function assistantConversation(array $in): array
{
    $raw = is_array($in['messages'] ?? null) ? array_slice($in['messages'], -ASSISTANT_MAX_TURNS) : [];
    $messages = [];
    foreach ($raw as $message) {
        $role = $message['role'] ?? '';
        $content = is_string($message['content'] ?? null) ? trim($message['content']) : '';
        if (!in_array($role, ['user', 'assistant'], true) || $content === '') continue;
        $content = mb_substr($content, 0, ASSISTANT_MAX_CHARS);
        // The API expects alternating roles: merge consecutive turns from the same side.
        if ($messages && $messages[count($messages) - 1]['role'] === $role) {
            $messages[count($messages) - 1]['content'] .= "\n\n" . $content;
        } else {
            $messages[] = ['role' => $role, 'content' => $content];
        }
    }
    while ($messages && $messages[0]['role'] !== 'user') array_shift($messages);
    if (!$messages || $messages[count($messages) - 1]['role'] !== 'user') {
        mError(422, 'invalid_message', t('Écrivez votre question.', 'Type your question.'), ['messages' => t('Écrivez votre question.', 'Type your question.')]);
    }
    return $messages;
}

/** Contract facts the assistant may quote. Nothing identifying, nothing medical. */
function assistantContext(array $a): string
{
    $lines = [
        'Plan: ' . ($a['entreprise_nom'] ?: 'company plan') . ' (managed by ' . ($a['org_name'] ?: 'the insurer') . ')',
        'Member status: ' . $a['statut'],
        'Default coverage rate: ' . (int)round((float)($a['taux_prise_en_charge'] ?? 0)) . ' %',
    ];
    $annual = (int)($a['plafond_annuel'] ?? 0);
    if ($annual > 0) $lines[] = 'Annual limit: ' . number_format($annual, 0, ',', ' ') . ' FCFA (consumption is shown on the Home screen)';

    $stmt = db()->prepare('SELECT libelle, taux_couverture, plafond_acte, periode_plafond FROM baremes WHERE entreprise_id = ? AND org_id = ? AND is_active = 1 ORDER BY libelle');
    $stmt->execute([$a['entreprise_id'], $a['org_id']]);
    foreach ($stmt->fetchAll() as $rule) {
        $line = '- ' . $rule['libelle'] . ': ' . (int)round((float)$rule['taux_couverture']) . ' %';
        if ((int)$rule['plafond_acte'] > 0) {
            $line .= ', limit ' . number_format((int)$rule['plafond_acte'], 0, ',', ' ') . ' FCFA' . ($rule['periode_plafond'] ? ' (' . str_replace('_', ' ', $rule['periode_plafond']) . ')' : '');
        }
        $lines[] = $line;
    }
    return implode("\n", $lines);
}

function assistantSystem(array $a): array
{
    $language = mLang() === 'en' ? 'English' : 'French';
    $guide = <<<TXT
You are the in-app assistant of a health insurance mobile app used by insured members in Senegal. Members ask you short, practical questions from their phone: how to do something in the app, what a screen or a status means, or what their plan covers. You are a first line of help; a human account manager at the insurer handles everything that needs a decision or access to a file.

What the app offers, so you can guide people to the right place:
- Home: plan summary, annual limit and how much of it has been used, alerts.
- Card: the member's digital insurance card with a QR code that refreshes about every minute. The member shows it at a network provider (pharmacy, clinic, laboratory) so the provider can check their cover and apply direct billing ("tiers payant") when available.
- Claims: lists reimbursement claims and their status. "New claim" walks through choosing the type of care, photographing or importing the invoice and supporting documents, checking the amounts, and submitting. A claim can be saved as a draft and finished later. After submission the insurer reviews it; the status and any settlement appear in the claim's detail.
- Network: list and map of partner providers, with search and filters by type. Positions shown as approximate are estimated from the city, so the address is the reference.
- Profile: contact details, family members, "Dossier médical" / "Medical record" (documents the member stores themselves, encrypted; not a file kept by the insurer or a doctor), notifications, language (French or English), appearance, biometric lock, password change, account deletion request, the assistant (you) and "Give feedback" ("Donner mon avis").
- Sign-in uses the username and password given by the insurer or the employer. Password resets and new accounts are handled by the account manager, not in the app.

How to answer:
- Reply in the language the member writes in; if unclear, use {$language}. Plain text only, no Markdown, since the app shows your text as-is. Keep it short enough to read on a phone: usually two to five sentences, or a few numbered steps for a how-to.
- For questions about cover, use only the contract facts given below. They are the full extent of what you know about this member: you cannot see their claims, payments, documents or personal details. When the answer depends on something you cannot see (the status of a specific claim, why a claim was refused, a missing payment), say where in the app they can check it, and that their account manager can look into the file.
- Amounts are in FCFA. Do not estimate a reimbursement for a specific invoice beyond stating the applicable rate and limit, because the insurer applies rules you do not have (exclusions, waiting periods, agreed tariffs).
- You are not a health professional. For questions about symptoms, treatments or medicines, say so kindly and suggest a doctor or pharmacist; in an emergency, tell them to call local emergency services (SAMU: 1515 in Senegal). If a member shares medical details, do not repeat them back; answer the practical insurance question only.
- If the member reports a bug or has a suggestion, invite them to use Profile > "Give feedback" ("Donner mon avis" in French) so the team receives it.
- Stay on the app and the member's health insurance. For anything else, say briefly that you can only help with those.
- If you are not sure, say so rather than guessing. A wrong answer about cover can cost the member money.
TXT;
    return [
        ['type' => 'text', 'text' => $guide],
        ['type' => 'text', 'text' => "Contract facts for this member:\n" . assistantContext($a)],
    ];
}

/** POSTs JSON and returns [status, decoded body]. Status 0 means the request could not be made. */
function assistantPost(string $url, array $headers, array $payload): array
{
    $body = json_encode($payload, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => $body,
            CURLOPT_HTTPHEADER => $headers,
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_CONNECTTIMEOUT => 10,
            CURLOPT_TIMEOUT => ASSISTANT_TIMEOUT,
        ]);
        $response = curl_exec($ch);
        $status = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
        curl_close($ch);
        if ($response === false) return [0, []];
    } else {
        $context = stream_context_create(['http' => [
            'method' => 'POST',
            'header' => implode("\r\n", $headers),
            'content' => $body,
            'timeout' => ASSISTANT_TIMEOUT,
            'ignore_errors' => true,
        ]]);
        $response = @file_get_contents($url, false, $context);
        if ($response === false) return [0, []];
        $status = preg_match('#^HTTP/\S+\s+(\d{3})#', $http_response_header[0] ?? '', $m) ? (int)$m[1] : 0;
    }
    $decoded = json_decode($response, true);
    return [$status, is_array($decoded) ? $decoded : []];
}

function assistantUnavailable(): never
{
    mError(503, 'assistant_unavailable', t(
        "L'assistant est momentanément indisponible. Réessayez plus tard ou contactez votre gestionnaire.",
        'The assistant is temporarily unavailable. Try again later or contact your account manager.'));
}

function assistantReply(array $a, array $in): never
{
    $key = assistantKey();
    if ($key === null) assistantUnavailable();
    $messages = assistantConversation($in);

    $stmt = db()->prepare('SELECT COUNT(*) FROM mobile_assistant_usage WHERE adherent_id = ? AND created_at > (NOW() - INTERVAL 1 HOUR)');
    $stmt->execute([$a['id']]);
    if ((int)$stmt->fetchColumn() >= ASSISTANT_HOURLY_LIMIT) {
        mError(429, 'too_many_requests', t(
            'Vous avez posé beaucoup de questions. Réessayez dans une heure.',
            'You have asked a lot of questions. Try again in an hour.'));
    }

    [$status, $response] = assistantPost(
        getenv('ASSISTANT_API_URL') ?: ASSISTANT_API_URL,
        [
            'Content-Type: application/json',
            'x-api-key: ' . $key,
            'anthropic-version: 2023-06-01',
            // If the model declines a request, the API retries it on its recommended fallback model.
            'anthropic-beta: server-side-fallback-2026-07-01',
        ],
        [
            'model' => getenv('ASSISTANT_MODEL') ?: ASSISTANT_DEFAULT_MODEL,
            'max_tokens' => 4000,
            'output_config' => ['effort' => 'low'],
            'fallbacks' => 'default',
            'system' => assistantSystem($a),
            'messages' => $messages,
        ]
    );

    if ($status !== 200) {
        error_log('mobile assistant: HTTP ' . $status . ' ' . ($response['error']['type'] ?? ''));
        assistantUnavailable();
    }

    $usage = $response['usage'] ?? [];
    db()->prepare('INSERT INTO mobile_assistant_usage (adherent_id, input_tokens, output_tokens) VALUES (?, ?, ?)')
        ->execute([$a['id'], (int)($usage['input_tokens'] ?? 0), (int)($usage['output_tokens'] ?? 0)]);

    $text = '';
    if (($response['stop_reason'] ?? '') !== 'refusal') {
        foreach ($response['content'] ?? [] as $block) {
            if (($block['type'] ?? '') === 'text') $text .= $block['text'];
        }
    }
    $text = trim($text);
    if ($text === '') {
        $text = t(
            "Je ne peux pas répondre à cette question. Pour le reste, votre gestionnaire peut vous aider.",
            "I can't help with that question. For anything else, your account manager can help.");
    }
    mJson(['message' => ['role' => 'assistant', 'content' => $text]]);
}
